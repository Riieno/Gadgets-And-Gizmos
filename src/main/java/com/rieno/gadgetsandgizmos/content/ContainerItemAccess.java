package com.rieno.gadgetsandgizmos.content;

/*--------------------------------------------------------##---------------------------------------------------------

=======================================================================================================================
                                                        IMPORTS
=======================================================================================================================

------------------------------------------------------------##-----------------------------------------------------*/

import org.jetbrains.annotations.Nullable;

import java.util.function.ToLongFunction;

// Read item handlers from container items
final class ContainerItemAccess {
    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                        PRELOAD / SETUP
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Initialize the container item
    private ContainerItemAccess() {
    }

    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                           Functions
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Select the container item
    static <T> @Nullable T select(@Nullable T attachedHandler, Iterable<T> handlers,
                                  ToLongFunction<T> amountReader) {
        if (attachedHandler != null) {
            return attachedHandler;
        }
        T fullestHandler = null;
        long fullestAmount = -1L;
        for (T handler : handlers) {
            if (handler == null) {
                continue;
            }
            long amount = Math.max(0L, amountReader.applyAsLong(handler));
            if (amount > fullestAmount) {
                fullestHandler = handler;
                fullestAmount = amount;
            }
        }
        return fullestHandler;
    }
}
