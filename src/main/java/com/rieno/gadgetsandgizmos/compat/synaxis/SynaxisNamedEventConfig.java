package com.rieno.gadgetsandgizmos.compat.synaxis;

/*--------------------------------------------------------##---------------------------------------------------------

=======================================================================================================================
                                                        IMPORTS
=======================================================================================================================

------------------------------------------------------------##-----------------------------------------------------*/

import com.mojang.serialization.Codec;
import com.verr1.synaxis.foundation.cimulink.core.component.ComponentConfig;

// Persist the Named Event topic selected by one Synaxis component
public record SynaxisNamedEventConfig(String name) implements ComponentConfig {
    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                           Constants
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    public static final Codec<SynaxisNamedEventConfig> CODEC = Codec.STRING.xmap(
            SynaxisNamedEventConfig::new, SynaxisNamedEventConfig::name);

    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                        PRELOAD / SETUP
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Normalize the event topic while preserving Synaxis's simple string configuration model
    public SynaxisNamedEventConfig {
        name = name == null ? "" : name.strip();
        if (name.length() > 128) {
            name = name.substring(0, 128);
        }
    }
}
