/*--------------------------------------------------------##---------------------------------------------------------

=======================================================================================================================
                                                        IMPORTS
=======================================================================================================================

------------------------------------------------------------##-----------------------------------------------------*/

import net.minecraft.core.Direction;

// Rotate joystick input through its mounted orientation
public final class AnalogueJoystickOrientation {
    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                        PRELOAD / SETUP
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Initialize the analogue joystick orientation
    private AnalogueJoystickOrientation() {
    }

    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                           Functions
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Get the y rotation degrees
    static float yRotationDegrees(Direction facing) {
        return switch (facing) {
            case SOUTH -> 180.0F;
            case EAST -> -90.0F;
            case WEST -> 90.0F;
            default -> 0.0F;
        };
    }

    // Get the logical facing
    static Direction logicalFacing(Direction facing) {
        return facing;
    }

    // Get the local drag
    public static float[] localDrag(float blockRight, float blockForward) {
        float localX = blockRight == 0.0F ? 0.0F : -blockRight;
        return new float[]{localX, blockForward};
    }
}
