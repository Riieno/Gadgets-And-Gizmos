import net.minecraft.world.entity.player.Player;

// Handle shared player interaction gestures
public final class CTInteractionGestures {
    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                        PRELOAD / SETUP
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Initialize the CT interaction gestures
    private CTInteractionGestures() {
    }

    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                           Functions
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Check if this should open config menu
    public static boolean shouldOpenConfigMenu(Player player) {

        return player.isShiftKeyDown();
    }
}
