package com.rieno.gadgetsandgizmos.util;

/*--------------------------------------------------------##---------------------------------------------------------

=======================================================================================================================
                                                        IMPORTS
=======================================================================================================================

------------------------------------------------------------##-----------------------------------------------------*/

import java.util.function.IntSupplier;

// Expose Oxidized fuel storage
public final class OxidizedFuelStorageAccess {
    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                           Constants
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    private static final ThreadLocal<Integer> ALLOW_DEPTH = ThreadLocal.withInitial(() -> 0);

    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                        PRELOAD / SETUP
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Initialize the oxidized fuel storage
    private OxidizedFuelStorageAccess() {
    }

    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                           Functions
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Check if this is allowed
    public static boolean isAllowed() {
        return ALLOW_DEPTH.get() > 0;
    }

    // Get the allow
    public static int allow(IntSupplier supplier) {
        ALLOW_DEPTH.set(ALLOW_DEPTH.get() + 1);
        try {
            return supplier.getAsInt();
        } finally {
            int nextDepth = ALLOW_DEPTH.get() - 1;
            if (nextDepth <= 0) {
                ALLOW_DEPTH.remove();
            } else {
                ALLOW_DEPTH.set(nextDepth);
            }
        }
    }
}
