package com.rieno.gadgetsandgizmos.neoforge.network;

/*--------------------------------------------------------##---------------------------------------------------------

=======================================================================================================================
                                                        IMPORTS
=======================================================================================================================

------------------------------------------------------------##-----------------------------------------------------*/

import net.minecraft.nbt.CompoundTag;
import net.minecraft.network.RegistryFriendlyByteBuf;

// Send Graph NBT Payload Codec
final class GraphNbtPayloadCodec {
    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                        PRELOAD / SETUP
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Initialize the graph NBT payload codec
    private GraphNbtPayloadCodec() {
    }

    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                           Functions
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Write graph NBT through the bounded library codec
    static void write(RegistryFriendlyByteBuf buffer, CompoundTag tag){
        com.rieno.gadgetsandgizmos.lib.network.CompressedTagCodec.write(buffer, tag == null ? new CompoundTag() : tag);
    }

    // Read compressed graphs with a separate expanded allocation limit
    static CompoundTag read(RegistryFriendlyByteBuf buffer){
        return com.rieno.gadgetsandgizmos.lib.network.CompressedTagCodec.read(buffer);
    }
}
