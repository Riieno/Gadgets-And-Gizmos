import dev.simulated_team.simulated.content.blocks.rope.RopeStrandHolderBehavior;
import dev.simulated_team.simulated.content.blocks.rope.strand.client.ClientRopeStrand;
import net.minecraft.world.phys.AABB;
import org.jetbrains.annotations.Nullable;

// Calculate the client launcher anchor bounds
public final class EntityLauncherAnchorClientBounds {
    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                        PRELOAD / SETUP
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Initialize the entity launcher anchor client bounds
    private EntityLauncherAnchorClientBounds() {
    }

    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                           Functions
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Get the rope bounds
    public static @Nullable AABB getRopeBounds(RopeStrandHolderBehavior ropeHolder) {
        ClientRopeStrand rope = ropeHolder.getClientStrand();
        return rope == null ? null : rope.getBounds();
    }
}
