package com.rieno.gadgetsandgizmos.content;

/*--------------------------------------------------------##---------------------------------------------------------

=======================================================================================================================
                                                        IMPORTS
=======================================================================================================================

------------------------------------------------------------##-----------------------------------------------------*/

import net.minecraft.core.Direction;
import net.minecraft.util.Mth;
import net.minecraft.world.phys.Vec3;

// Calculate embedded controller surface offsets
public final class ControllerEmbeddedMount {
    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                           Constants
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    public static final int PIXELS_PER_BLOCK = 16;

    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                        PRELOAD / SETUP
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Initialize the controller embedded mount
    private ControllerEmbeddedMount() {
    }

    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                           Functions
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Get the surface offset pixels
    static int surfaceOffsetPixels(Vec3 localHit, Direction surfaceNormal) {
        double distance = switch (surfaceNormal) {
            case EAST -> localHit.x;
            case WEST -> 1.0D - localHit.x;
            case UP -> localHit.y;
            case DOWN -> 1.0D - localHit.y;
            case SOUTH -> localHit.z;
            case NORTH -> 1.0D - localHit.z;
        };
        return Mth.clamp((int) Math.round(distance * PIXELS_PER_BLOCK), 0, PIXELS_PER_BLOCK);
    }
}
