package com.rieno.gadgetsandgizmos.content;

// Calculate Vector Bearing piston movement
public final class VectorBearingPistonMath {
    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                           Constants
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    private static final double REST_EXTENSION = 0.1875D;
    private static final double MIN_EXTENSION = 0.0625D;
    private static final double MAX_EXTENSION = 0.75D;

    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                        PRELOAD / SETUP
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Initialize the vector bearing piston math
    private VectorBearingPistonMath() {
    }

    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                           Functions
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Get the extension
    public static double extension(double radialDotTiltedNormal, double normalDotTiltedNormal) {
        if (Math.abs(normalDotTiltedNormal) < 1.0E-6D) {
            return REST_EXTENSION;
        }
        double planeIntersection = -radialDotTiltedNormal / normalDotTiltedNormal;
        return Math.max(MIN_EXTENSION, Math.min(MAX_EXTENSION, planeIntersection + REST_EXTENSION));
    }
}
