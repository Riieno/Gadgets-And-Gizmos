package com.rieno.gadgetsandgizmos.registry;

/*--------------------------------------------------------##---------------------------------------------------------

=======================================================================================================================
                                                        IMPORTS
=======================================================================================================================

------------------------------------------------------------##-----------------------------------------------------*/

import net.minecraft.network.chat.Component;
import net.minecraft.resources.ResourceLocation;

// Store one creative tab section
public record CTCreativeTabSection(
        String id,
        Component title,
        ResourceLocation bannerTexture,
        int priority
) implements Comparable<CTCreativeTabSection> {

    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                           Functions
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Compare creative tab sections
    @Override
    public int compareTo(CTCreativeTabSection other) {
        return Integer.compare(this.priority, other.priority);
    }
}
